// Embeds the invoice fonts and logo into a generated TypeScript module as
// base64, so the PDF renderer never reads from disk at runtime.
//
// Why: files under public/ are served by the CDN and are NOT included in the
// serverless function's filesystem on Vercel, so `fs.readFileSync` there throws
// ENOENT and the PDF silently fails to render. Compiling the bytes into the
// bundle removes that dependency entirely — it works the same locally and in
// production.
//
// Re-run after changing the logo or the embedded font weights:
//   node scripts/embed-invoice-assets.mjs

import fs from "node:fs"
import path from "node:path"

const root = process.cwd()
const pub = (...p) => path.join(root, "public", ...p)

const b64 = (file) => fs.readFileSync(file).toString("base64")

const fontRegular = b64(pub("fonts", "Geist-Regular.ttf"))
const fontSemibold = b64(pub("fonts", "Geist-SemiBold.ttf"))
const logo = b64(pub("images", "logo1.png"))

const out = `// AUTO-GENERATED by scripts/embed-invoice-assets.mjs — do not edit by hand.
//
// The invoice fonts and logo, base64-encoded and compiled into the bundle so
// the PDF renderer has no filesystem dependency at runtime. See the script for
// why this matters on Vercel.

export const GEIST_REGULAR = "data:font/ttf;base64,${fontRegular}"

export const GEIST_SEMIBOLD = "data:font/ttf;base64,${fontSemibold}"

export const LOGO_PNG = "data:image/png;base64,${logo}"
`

const dest = path.join(root, "lib", "invoicing", "assets.generated.ts")
fs.writeFileSync(dest, out)

const kb = (n) => Math.round((n / 1024) * 10) / 10
console.log(`wrote ${dest}`)
console.log(`  Geist-Regular  ${kb(fontRegular.length)} KB (base64)`)
console.log(`  Geist-SemiBold ${kb(fontSemibold.length)} KB (base64)`)
console.log(`  logo1.png      ${kb(logo.length)} KB (base64)`)
